    public int getNote(String noteName)
    {
        int temp = 0;
        boolean n = noteName.contains("n");
        // boolean p = noteName.contains("p");
        String[] noteNameArray = noteName.split("n|p");
        int octave = (n ? -1 : 1) * Integer.parseInt(noteNameArray[1].substring(0));
        String[] friendlyNoteNames = { "C", "Cs", "D", "Ds", "E", "F", "Fs", "G", "Gs", "A", "As", "B" };
        for (int i = 0; i < friendlyNoteNames.length; i++)
        {
            if (friendlyNoteNames[i].equals(noteNameArray[0])) temp = i;
        }
        return temp + (12 + (octave * 12));
    }

