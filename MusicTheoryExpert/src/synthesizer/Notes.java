    public ArrayList<Integer> getMajorScale(int note)
    {
        ArrayList<Integer> scale = new ArrayList<Integer>();
        scale.add(note);
        scale.add(note + second);
        scale.add(note + third);
        scale.add(note + fourth);
        scale.add(note + fifth);
        scale.add(note + sixth);
        scale.add(note + seventh);
        return scale;
    }

    public ArrayList<Integer> getMinorScale(int note)
    {
        ArrayList<Integer> scale = new ArrayList<Integer>();
        scale.add(note);
        scale.add(note + second);
        scale.add(note + third - 1);
        scale.add(note + fourth);
        scale.add(note + fifth);
        scale.add(note + sixth - 1);
        scale.add(note + seventh);
        return scale;
    }

    public ArrayList<Integer> get1Chord(ArrayList<Integer> scale)
    {
        ArrayList<Integer> chord = new ArrayList<Integer>();
        chord.add(scale.get(0));
        chord.add(scale.get(2));
        chord.add(scale.get(4));
        return chord;
    }

    public ArrayList<Integer> get4Chord(ArrayList<Integer> scale)
    {
        ArrayList<Integer> chord = new ArrayList<Integer>();
        chord.add(scale.get(3));
        chord.add(scale.get(5));
        chord.add(scale.get(0) + 12);
        return chord;
    }

    public ArrayList<Integer> get5Chord(ArrayList<Integer> scale)
    {
        ArrayList<Integer> chord = new ArrayList<Integer>();
        chord.add(scale.get(4));
        chord.add(scale.get(6));
        chord.add(scale.get(1) + 12);
        return chord;
    }

    public ArrayList<Integer> octaveAdjuster(ArrayList<Integer> notes, int octave)
    {
        ArrayList<Integer> adjustedNotes = new ArrayList<Integer>();
        for (int i = 0; i < notes.size(); i++)
        {
            adjustedNotes.add(notes.get(i) + (12 * octave));
        }
        return adjustedNotes;
    }

    public ArrayList<Integer> getInversion(ArrayList<Integer> chord, int inversion)
    {
        ArrayList<Integer> invertedChord = new ArrayList<Integer>();
        for (int i = 0; i < chord.size(); i++)
        {
            if (i < inversion) invertedChord.add(chord.get(i) + 12);
            else
                invertedChord.add(chord.get(i));
        }
        return invertedChord;
    }

    public ArrayList<ArrayList<Integer>> getAccompanyingChords(ArrayList<Integer> rightHand, ArrayList<Integer> scale)
    {
        ArrayList<ArrayList<Integer>> chords = new ArrayList<ArrayList<Integer>>();
        ArrayList<ArrayList<Integer>> leftHand = new ArrayList<ArrayList<Integer>>();
        chords.add(get1Chord(scale));
        chords.add(getInversion(get4Chord(octaveAdjuster(scale, -1)), 2));
        chords.add(getInversion(get5Chord(octaveAdjuster(scale, -1)), 1));
        for (int i = 0; i < rightHand.size(); i++)
        {
            if (rightHand.get(i) % 12 == scale.get(0) % 12 || rightHand.get(i) % 12 == scale.get(2) % 12)
            {
                leftHand.add(chords.get(0));
            }
            else if (rightHand.get(i) % 12 == scale.get(3) % 12 || rightHand.get(i) % 12 == scale.get(5) % 12)
            {
                leftHand.add(chords.get(1));
            }
            else if (rightHand.get(i) % 12 == scale.get(1) % 12 || rightHand.get(i) % 12 == scale.get(4) % 12
                            || rightHand.get(i) % 12 == scale.get(6) % 12)
            {
                leftHand.add(chords.get(2));
            }
        }
        return leftHand;
    }

